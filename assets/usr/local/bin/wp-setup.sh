#!/bin/bash
# Bootstrap pending WordPress sites:
#   for each site in $STORE_PATH .sites[], if the .installed marker is missing,
#   create the database, lay down WP files, generate wp-config.php, and run
#   wp core install.
#
# Idempotent: completed sites are left alone. Designed to be run as a oneshot
# at every setupMain re-evaluation. Imports of existing sites go through
# WordPress plugins (BackupBuddy, Duplicator, All-in-One WP Migration, etc.)
# — install on a fresh site, restore via the plugin.
set -euo pipefail

: "${STORE_PATH:?STORE_PATH not set}"
: "${DB_HOST:?DB_HOST not set}"
: "${DB_ROOT_PASSWORD:?DB_ROOT_PASSWORD not set}"
: "${SITES_ROOT:?SITES_ROOT not set}"

CORE_SRC=/usr/local/share/wordpress-core

mkdir -p "$SITES_ROOT"

mariadb_run() {
  mariadb -h "$DB_HOST" -u root -p"$DB_ROOT_PASSWORD" "$@"
}

wait_for_db() {
  for _ in $(seq 1 60); do
    if mariadb_run -e 'SELECT 1' >/dev/null 2>&1; then
      return 0
    fi
    sleep 1
  done
  echo "MariaDB never became ready" >&2
  exit 1
}

gen_secret() {
  tr -dc 'a-zA-Z0-9!@#$%^&*()-_=+' </dev/urandom | head -c 64
}

shell_escape() {
  printf "%s" "$1" | sed "s/'/'\\\\''/g"
}

write_wp_config() {
  local site_dir="$1"
  local db_name="$2"
  local cfg="$site_dir/wp-config.php"
  local db_pass_escaped
  db_pass_escaped=$(shell_escape "$DB_ROOT_PASSWORD")

  cat > "$cfg" <<PHP
<?php
// Generated by wordpress-startos. Do not edit by hand.

// StartOS terminates TLS at the platform edge and forwards plain HTTP to
// us, so \$_SERVER['HTTPS'] is never set. Force it on so WordPress's
// is_ssl()-driven redirect logic agrees with the https:// URLs we emit
// below — otherwise /wp-admin loops between thinking the canonical URL
// is reachable and not.
\$_SERVER['HTTPS'] = 'on';

\$_host = \$_SERVER['HTTP_HOST'] ?? \$_SERVER['SERVER_NAME'] ?? 'localhost';
define('WP_HOME',    'https://' . \$_host);
define('WP_SITEURL', 'https://' . \$_host);

define('DB_NAME',     '$db_name');
define('DB_USER',     'root');
define('DB_PASSWORD', '$db_pass_escaped');
define('DB_HOST',     '$DB_HOST');
define('DB_CHARSET',  'utf8mb4');
define('DB_COLLATE',  '');

\$table_prefix = 'wp_';

define('AUTH_KEY',         '$(gen_secret)');
define('SECURE_AUTH_KEY',  '$(gen_secret)');
define('LOGGED_IN_KEY',    '$(gen_secret)');
define('NONCE_KEY',        '$(gen_secret)');
define('AUTH_SALT',        '$(gen_secret)');
define('SECURE_AUTH_SALT', '$(gen_secret)');
define('LOGGED_IN_SALT',   '$(gen_secret)');
define('NONCE_SALT',       '$(gen_secret)');

define('WP_DEBUG', false);
define('WP_DEBUG_DISPLAY', false);
define('WP_DEBUG_LOG', false);

// Core upgrades are managed by the wordpress-startos package, not by WP itself.
define('WP_AUTO_UPDATE_CORE', false);

// Disable wp-cron's per-request loopback HTTP call. The wordpress-startos
// package runs cron from a sidecar daemon every 5 minutes — leaving the
// loopback enabled causes page timeouts when the public hostname can't
// resolve from inside the container (during DNS propagation, cert
// provisioning, etc.).
define('DISABLE_WP_CRON', true);

// Force HTTPS for /wp-admin. With \$_SERVER['HTTPS'] forced above this is
// already effective; setting the constant is defense in depth.
define('FORCE_SSL_ADMIN', true);

// Prevent in-admin editing of theme/plugin PHP files.
define('DISALLOW_FILE_EDIT', true);

// Allow direct filesystem writes (no FTP prompt) for plugin installs.
define('FS_METHOD', 'direct');

if ( !defined('ABSPATH') ) define('ABSPATH', __DIR__ . '/');
require_once ABSPATH . 'wp-settings.php';
PHP
  chmod 600 "$cfg"
}

install_fresh() {
  local site_dir="$1"
  local db_name="$2"
  local name="$3"
  local admin_user="$4"
  local admin_password="$5"
  local admin_email="$6"

  mariadb_run -e "CREATE DATABASE IF NOT EXISTS \`$db_name\` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci"

  cp -a "$CORE_SRC"/. "$site_dir/"
  write_wp_config "$site_dir" "$db_name"

  wp --path="$site_dir" --allow-root core install \
    --url="http://localhost" \
    --title="$name" \
    --admin_user="$admin_user" \
    --admin_password="$admin_password" \
    --admin_email="$admin_email" \
    --skip-email
}

wait_for_db

jq -c '.sites[]?' "$STORE_PATH" | while read -r site; do
  id=$(echo "$site" | jq -r .id)
  name=$(echo "$site" | jq -r .name)
  admin_user=$(echo "$site" | jq -r .adminUser)
  admin_password=$(echo "$site" | jq -r .adminPassword)
  admin_email=$(echo "$site" | jq -r .adminEmail)

  site_dir="$SITES_ROOT/$id"
  db_name="wp_$id"

  if [ -f "$site_dir/.installed" ]; then
    continue
  fi

  echo "Setting up site '$name' ($id)…"
  mkdir -p "$site_dir"
  install_fresh "$site_dir" "$db_name" "$name" "$admin_user" "$admin_password" "$admin_email"
  chown -R www-data:www-data "$site_dir"
  touch "$site_dir/.installed"
  echo "Site '$name' ready."
done
